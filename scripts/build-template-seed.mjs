#!/usr/bin/env node
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
const versions = [
  { version: '1.0.0', base: 'templates/legacy/base-layout-v1.hbs', header: 'templates/legacy/header-v1.hbs' },
  { version: '1.1.0', base: 'templates/base-layout.hbs', header: 'templates/partials/header.hbs' }
];
const sqlLiteral = (v) => "'" + v.replaceAll("'", "''") + "'";
const maps = {
  SIRIKAP: {
    kategori: { A:'AKSES & DASHBOARD', B:'PARAMETER - DAFTAR OPD', C:'PARAMETER - KECAMATAN', D:'PARAMETER - GAMPONG', E:'PARAMETER - URUSAN', F:'INOVASI DAERAH - DAFTAR & INDIKATOR', G:'INOVASI DAERAH - TAMBAH', H:'KELITBANGAN & LAPORAN', I:'UTILITY - PENGGUNA & GROUP', J:'UTILITY - OTORITAS & PENGATURAN', K:'NAVIGASI & LAINNYA', L:'GATE ULO YANG BELUM TERBUKTI' },
    pages: { 2:{fromOrder:1,toOrder:18}, 3:{fromOrder:19,toOrder:36}, 4:{fromOrder:37,toOrder:54}, 5:{fromOrder:55,toOrder:71} },
    officialPages: { 2:{fromOrder:1,toOrder:20}, 3:{fromOrder:21,toOrder:42}, 4:{fromOrder:43,toOrder:60}, 5:{fromOrder:61,toOrder:71} }
  },
  SIMPEG: {
    kategori: { A:'AUTENTIKASI & OTORISASI', B:'DATA PEGAWAI', C:'MUTASI & PROMOSI', D:'ABSENSI', E:'LAPORAN KEPEGAWAIAN', F:'UTILITY' },
    pages: { 2:{fromOrder:1,toOrder:18}, 3:{fromOrder:19,toOrder:36}, 4:{fromOrder:37,toOrder:54}, 5:{fromOrder:55,toOrder:71} }
  }
};
let sql = `-- Generated by node scripts/build-template-seed.mjs; do not edit manually.\nSET search_path TO ulo_uat, public;\n`;
let migration = `-- New immutable BA/ULO/UAT template version. Never UPDATE published v1.0.0 documents.\nSET search_path TO ulo_uat, public;\n`;
for (const version of versions) {
  const layout=await fs.readFile(version.base, 'utf8');
  const header=await fs.readFile(version.header, 'utf8');
  const partials={header};
  const hash=crypto.createHash('sha256').update(layout+JSON.stringify(partials)).digest('hex');
  for (const [code,obj] of Object.entries(maps)) {
    const pages=version.version==='1.1.0'?(obj.officialPages||obj.pages):obj.pages;
    const statement = `INSERT INTO templates (project_id,versi,nama,layout_hbs,partials,kategori_map,page_map,checksum,published)\nSELECT id,${sqlLiteral(version.version)},${sqlLiteral(version.version==='1.0.0'?code+' Form ULO':code+' Form BA ULO/UAT 1.1.0')},${sqlLiteral(layout)},${sqlLiteral(JSON.stringify(partials))}::jsonb,${sqlLiteral(JSON.stringify(obj.kategori))}::jsonb,${sqlLiteral(JSON.stringify(pages))}::jsonb,${sqlLiteral(hash)},TRUE\nFROM projects WHERE kode=${sqlLiteral(code)} ON CONFLICT (project_id,versi) DO NOTHING;\n`;
    sql += statement;
    if (version.version==='1.1.0') migration += statement;
  }
}
await fs.writeFile('db/seed-templates.sql', sql);
await fs.writeFile('db/migrations/20261121_official_ba_ulo_uat_v110.sql', migration);
console.log('Generated versioned db/seed-templates.sql (old published versions remain immutable)');
