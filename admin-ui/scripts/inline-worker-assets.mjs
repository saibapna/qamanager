import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const output = path.join(root, 'worker', 'generated-assets.mjs');
const assets = {};
async function visit(dir) {
  for (const ent of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) await visit(full);
    else if (ent.isFile()) {
      const key = '/' + path.relative(dist, full).split(path.sep).join('/');
      assets[key] = (await readFile(full)).toString('base64');
    }
  }
}
await visit(dist);
if (!assets['/index.html']) throw new Error('Vite output missing index.html');
const total = Object.values(assets).reduce((n, s) => n + s.length, 0);
if (total > 2_800_000) throw new Error(`Inlined assets too large (${total} bytes); use Workers Static Assets or Pages direct upload`);
await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, '// Generated by build:worker; do not commit.\nexport const assets = ' + JSON.stringify(assets) + ';\n');
console.log(`Inlined ${Object.keys(assets).length} static assets (${total} encoded bytes)`);
